      rescue => audio_err
        print " [Audio Error: #{audio_err.message}]"
      end
    end

    puts "OK: #{v[:word]}"
  rescue => e
    puts "ERROR: #{v[:word]} - #{e.message}"
  end
end

puts "Seeded #{Vocabulary.count} vocabs 🌸"


